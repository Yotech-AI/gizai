// Tests for scripts/version-only.mjs (GA-145), which tells CI and Install that a pull request into main only bumps
// Gizai's version. Each test makes a small git repository with Gizai's five version files at 0.9.1 on main, and a
// branch that bumps them to 0.10.0, with or without something else.
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, describe, expect, it } from "vitest";

const SCRIPT = fileURLToPath(new URL("./version-only.mjs", import.meta.url));
const scratch = mkdtempSync(join(tmpdir(), "version-only-"));
afterAll(() => rmSync(scratch, { recursive: true, force: true }));

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

// The repository's files with Gizai at `version`. Each option gives one place its own version instead.
function tree(version, { lock = version, npm = version, tauri = version, anyhow = "1.0.98", logos = "0.9.1" } = {}) {
  return {
    "Cargo.toml": [
      "[workspace]",
      'resolver = "3"',
      'members = ["crates/gizai-core", "src-tauri"]',
      "",
      "[workspace.package]",
      'edition = "2024"',
      'license = "MIT"',
      `version = "${version}"`,
      "",
      "[workspace.dependencies]",
      'anyhow = "1"',
      "",
    ].join("\n"),
    "Cargo.lock": [
      "# This file is automatically @generated by Cargo.",
      "# It is not intended for manual editing.",
      "version = 4",
      "",
      "[[package]]",
      'name = "anyhow"',
      `version = "${anyhow}"`,
      'source = "registry+https://github.com/rust-lang/crates.io-index"',
      'checksum = "e16d2d3311acee920a9eb8d33b8cbc1787ce4a264e85f964c2404b969bdcd487"',
      "",
      "[[package]]",
      'name = "gizai"',
      `version = "${version}"`,
      "dependencies = [",
      ' "anyhow",',
      ' "gizai-core",',
      "]",
      "",
      "[[package]]",
      'name = "gizai-core"',
      `version = "${lock}"`,
      "dependencies = [",
      ' "anyhow",',
      ' "logos",',
      "]",
      "",
      // A dependency that happens to be at Gizai's old version.
      "[[package]]",
      'name = "logos"',
      `version = "${logos}"`,
      'source = "registry+https://github.com/rust-lang/crates.io-index"',
      'checksum = "ff472f899b4ec2d99161c51f60ff7075eeb3097069a36050d8037a6325eb8154"',
      "",
    ].join("\n"),
    "package.json": json({
      name: "gizai",
      private: true,
      version: npm,
      type: "module",
      dependencies: { react: "^19.2.0" },
    }),
    "package-lock.json": json({
      name: "gizai",
      version: npm,
      lockfileVersion: 3,
      requires: true,
      packages: {
        "": { name: "gizai", version: npm, dependencies: { react: "^19.2.0" } },
        "node_modules/react": { version: "19.2.0", license: "MIT" },
      },
    }),
    "src-tauri/tauri.conf.json": json({ productName: "Gizai", version: tauri, identifier: "ai.gizai.app" }),
    "README.md": "# Gizai\n",
    "src/main.ts": "export const answer = 42;\n",
  };
}

function git(dir, ...args) {
  const run = spawnSync("git", args, { cwd: dir, encoding: "utf8" });
  if (run.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${run.stderr}`);
  return run.stdout.trim();
}

// Writes the files (null removes one) and commits them. Returns the commit.
function commit(dir, files, message) {
  for (const [path, text] of Object.entries(files)) {
    if (text === null) {
      rmSync(join(dir, path));
      continue;
    }
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
  }
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "--allow-empty", "-m", message);
  return git(dir, "rev-parse", "HEAD");
}

let repos = 0;

// A repository with Gizai 0.9.1 on main, and a branch `bump` off it with `files` committed over that.
function bump(files) {
  const dir = join(scratch, `repo-${++repos}`);
  mkdirSync(dir);
  git(dir, "init", "-q", "-b", "main");
  git(dir, "config", "user.name", "Gizai test");
  git(dir, "config", "user.email", "test@gizai.invalid");
  git(dir, "config", "commit.gpgsign", "false");
  git(dir, "config", "core.autocrlf", "false");
  const base = commit(dir, tree("0.9.1"), "Gizai 0.9.1");
  git(dir, "checkout", "-q", "-b", "bump");
  const head = commit(dir, files, "Bump version to 0.10.0");
  return { dir, base, head };
}

function versionOnly(dir, ...args) {
  const run = spawnSync(process.execPath, [SCRIPT, ...args], { cwd: dir, encoding: "utf8" });
  return { code: run.status, out: run.stdout.trim(), err: run.stderr.trim() };
}

const yes = { code: 0, out: "Version only: 0.9.1 to 0.10.0.", err: "" };
const no = (why) => ({ code: 1, out: `Not version only: ${why}`, err: "" });

describe("scripts/version-only.mjs", { timeout: 30_000 }, () => {
  it("says a real bump, 0.9.1 to 0.10.0 in all five files, is version only", () => {
    const { dir, base, head } = bump(tree("0.10.0"));
    expect(versionOnly(dir, base, head)).toEqual(yes);
    expect(versionOnly(dir, "main", "bump")).toEqual(yes);
  });

  it("looks only at what the branch changes, after main has moved on", () => {
    const { dir } = bump(tree("0.10.0"));
    git(dir, "checkout", "-q", "main");
    commit(dir, { "README.md": "# Gizai\n\nMore.\n" }, "Main moves on");
    expect(versionOnly(dir, "main", "bump")).toEqual(yes);
  });

  it("says the same as CI asks it: the pull request's merge commit against its first parent, main", () => {
    const { dir } = bump(tree("0.10.0"));
    git(dir, "checkout", "-q", "main");
    commit(dir, { "README.md": "# Gizai\n\nMore.\n" }, "Main moves on");
    git(dir, "merge", "-q", "--no-ff", "-m", "Merge pull request #1", "bump");
    expect(versionOnly(dir, "HEAD^1", "HEAD")).toEqual(yes);
  });

  it("says no to the bump plus one other changed line", () => {
    const pkg = tree("0.10.0")["package.json"].replace('"^19.2.0"', '"^19.2.1"');
    let { dir, base, head } = bump({ ...tree("0.10.0"), "package.json": pkg });
    expect(versionOnly(dir, base, head)).toEqual(no("package.json changes line 7 too."));

    const toml = tree("0.10.0")["Cargo.toml"].replace('edition = "2024"', 'edition = "2021"');
    ({ dir, base, head } = bump({ ...tree("0.10.0"), "Cargo.toml": toml }));
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.toml changes line 6 too."));
  });

  it("says no to the bump plus a line added or removed", () => {
    const toml = `${tree("0.10.0")["Cargo.toml"]}serde = "1"\n`;
    const { dir, base, head } = bump({ ...tree("0.10.0"), "Cargo.toml": toml });
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.toml adds or removes lines."));
  });

  it("says no to the bump plus another file, changed, added or removed", () => {
    let { dir, base, head } = bump({ ...tree("0.10.0"), "src/main.ts": "export const answer = 43;\n" });
    expect(versionOnly(dir, base, head)).toEqual(no("src/main.ts changes too."));

    ({ dir, base, head } = bump({ ...tree("0.10.0"), "docs/notes.md": "New.\n" }));
    expect(versionOnly(dir, base, head)).toEqual(no("docs/notes.md changes too."));

    ({ dir, base, head } = bump({ ...tree("0.10.0"), "README.md": null }));
    expect(versionOnly(dir, base, head)).toEqual(no("README.md changes too."));
  });

  it("says no to a dependency's version changed in Cargo.lock", () => {
    let { dir, base, head } = bump(tree("0.10.0", { anyhow: "1.0.99" }));
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.lock changes the version of anyhow too."));

    // Also when the dependency was at Gizai's old version and goes to the new one.
    ({ dir, base, head } = bump(tree("0.10.0", { logos: "0.10.0" })));
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.lock changes the version of logos too."));
  });

  it("says no to the files bumped to two different versions", () => {
    let { dir, base, head } = bump(tree("0.10.0", { npm: "0.10.1" }));
    expect(versionOnly(dir, base, head)).toEqual(no("package.json goes to 0.10.1, Cargo.toml to 0.10.0."));

    ({ dir, base, head } = bump(tree("0.10.0", { tauri: "0.11.0" })));
    expect(versionOnly(dir, base, head)).toEqual(
      no("src-tauri/tauri.conf.json goes to 0.11.0, Cargo.toml to 0.10.0."),
    );

    ({ dir, base, head } = bump(tree("0.10.0", { lock: "0.10.1" })));
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.lock goes to 0.10.1, Cargo.toml to 0.10.0."));
  });

  it("says no when one of the five files keeps the old version", () => {
    let { dir, base, head } = bump(tree("0.10.0", { tauri: "0.9.1" }));
    expect(versionOnly(dir, base, head)).toEqual(no("src-tauri/tauri.conf.json doesn't change."));

    ({ dir, base, head } = bump(tree("0.10.0", { lock: "0.9.1" })));
    expect(versionOnly(dir, base, head)).toEqual(no("Cargo.lock keeps the version of gizai-core at 0.9.1."));
  });

  it("says no when package-lock.json bumps a dependency at Gizai's old version too", () => {
    const files = tree("0.10.0");
    const lock = JSON.parse(files["package-lock.json"]);
    const before = JSON.parse(tree("0.9.1")["package-lock.json"]);
    before.packages["node_modules/tiny"] = { version: "0.9.1" };
    lock.packages["node_modules/tiny"] = { version: "0.10.0" };
    const { dir } = bump({});
    git(dir, "checkout", "-q", "main");
    const base = commit(dir, { "package-lock.json": json(before) }, "A dependency at 0.9.1");
    git(dir, "checkout", "-q", "-b", "bump-tiny");
    const head = commit(dir, { ...files, "package-lock.json": json(lock) }, "Bump version to 0.10.0");
    expect(versionOnly(dir, base, head)).toEqual(no("package-lock.json changes another 0.9.1 to 0.10.0 too."));
  });

  it("says no when a file changes its mode", () => {
    const { dir, base } = bump({});
    commit(dir, tree("0.10.0"), "Bump version to 0.10.0");
    git(dir, "update-index", "--chmod=+x", "package.json");
    git(dir, "commit", "-q", "-m", "Executable");
    expect(versionOnly(dir, base, "HEAD")).toEqual(no("package.json changes its mode."));
  });

  it("can't tell, with exit code 2, without two commits", () => {
    const { dir } = bump(tree("0.10.0"));
    const missing = versionOnly(dir, "main", "no-such-branch");
    expect(missing).toMatchObject({ code: 2, out: "" });
    expect(missing.err).toBe("version-only: no-such-branch is not a commit");

    expect(versionOnly(dir, "main")).toMatchObject({ code: 2, out: "" });
    expect(versionOnly(dir, "--help", "main")).toMatchObject({ code: 2, out: "" });
  });
});
